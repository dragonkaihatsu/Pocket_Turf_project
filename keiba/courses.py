"""競馬場の物理的な特性表（コース適性を「特性」で束ねるための土台）。

## なぜ特性で束ねるのか

コース適性15点は長く死んだままだった（全馬が中立値）。原因は、適性を
**「その馬が中山を走ったことがあるか」**で測ろうとしていたことにある。
手元の9-12Rデータでは1頭あたりの出走数が少なく、特定1場での実績を持つ馬は
ほとんどいない。

特性で束ねると母数が変わる。「中山の実績」は中山だけだが、
**「小回りの実績」は中山・福島・小倉・札幌・函館の5場ぶん**が入る。
同じデータ量で1頭あたりの母数が数倍になる。

CLAUDE.mdの「中山⇔福島は小回り・右回り・直線が短いという共通特性がある
ため類推材料として加点する」という既存ルールを、2場の特例ではなく
**全場を特性で分類する形に一般化**したもの。

## 設計原則との関係

新聞・馬柱に載っているものは市場が織り込んでいる（上がり3F・着順・
レースの格・騎手・血統）。一方、**「この馬は小回り5場では複勝率40%だが
広いコースでは10%」という対比はどこにも表示されない**。場別成績は
netkeibaの馬ページにあるが、特性で束ねた集計は無い。自動照合しなければ
見えない組み合わせなので、掘られていない可能性がある。

## 出典と注意

直線距離・高低差はJRAが公表しているコース図の値。芝の直線距離を採る
（ダートは各場で芝より短い）。**外回り・内回りがある場（阪神・京都・
中山・新潟）は外回りの値**を代表値にしている。同じ場でも内外で性質が
変わるため、レースごとの内外は別途判定が必要（現状の収集データには
内外の区別が入っていないため未対応）。
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Course:
    name: str
    mawari: str        # 右 / 左
    kibo: str          # 小回り / 広い
    shiba: str         # 洋芝 / 野芝主体
    saka: str          # 急坂 / 緩い上り / 平坦
    chokusen: float    # 芝の直線距離(m)。外回りがある場は外回り
    note: str = ""


# 直線距離は芝（外回りがある場は外回り）。
COURSES: dict[str, Course] = {
    # ── 広いコース ──
    "東京": Course("東京", "左", "広い", "野芝主体", "緩い上り", 525.9,
                   "残り450m付近から高低差2.0mの緩い上り。急坂ではない"),
    "阪神": Course("阪神", "右", "広い", "野芝主体", "急坂", 473.6,
                   "ゴール前に高低差約1.8mの急坂。内回り(356.5m)は別性質"),
    "京都": Course("京都", "右", "広い", "野芝主体", "平坦", 403.7,
                   "直線は平坦。特徴は3-4角の下り坂(高低差約4.3m)で、"
                   "中山・阪神の『ゴール前の急坂』とは逆の性質"),
    "中京": Course("中京", "左", "広い", "野芝主体", "急坂", 412.5,
                   "直線に高低差約2.0mの急坂。左回りの急坂は中京のみ"),
    "新潟": Course("新潟", "左", "広い", "野芝主体", "平坦", 658.7,
                   "外回りの直線658.7mは国内最長。内回りは358.7m"),
    # ── 小回りコース ──
    "中山": Course("中山", "右", "小回り", "野芝主体", "急坂", 310.0,
                   "ゴール前に高低差約2.2mの急坂。直線が短く坂がある組み合わせ"),
    "福島": Course("福島", "右", "小回り", "野芝主体", "平坦", 292.0),
    "小倉": Course("小倉", "右", "小回り", "野芝主体", "平坦", 293.0),
    "札幌": Course("札幌", "右", "小回り", "洋芝", "平坦", 266.1,
                   "芝は洋芝。コーナーが緩く小回りの中では例外的"),
    "函館": Course("函館", "右", "小回り", "洋芝", "平坦", 262.1,
                   "芝は洋芝。直線262.1mは国内最短"),
}

# 直線の長さを3帯に分ける境界(m)。実測値の自然な切れ目で取る:
#   262 266 292 293 310 | 403.7 412.5 473.6 525.9 | 658.7
# 最初に300で切ったところ中山(310m)が中京(412.5m)と同じ帯に入ってしまった。
# 100m以上違う場を同じ扱いにするのは適性の話として成立しない
#
# **注意: この軸は「小回り」とほぼ同じ分類になる**（短い帯＝小回り5場）。
# 独立した情報を持たないので、両方をそのまま加点すると同じ特性を二重に
# 数えることになる（CLAUDE.md「既に満点評価の馬には二重計上しない」）。
# 実質的に新潟外回りの658.7mだけを切り出す軸として機能する
CHOKUSEN_BANDS = ((0, 320, "短い(~320m)"),
                  (320, 560, "中間(320-560m)"),
                  (560, 9999, "長い(560m~)"))


def chokusen_band(course: str) -> str | None:
    c = COURSES.get(course)
    if c is None:
        return None
    for lo, hi, label in CHOKUSEN_BANDS:
        if lo <= c.chokusen < hi:
            return label
    return None


def traits(course: str, surface: str | None = None) -> dict[str, str]:
    """その競馬場の特性を {軸: 値} で返す。

    surface に「芝」「ダート」を渡すと、芝にしか意味の無い軸
    （洋芝か野芝か）をダートでは外す。洋芝適性はダートには存在しない
    概念なので、ダートで同じ軸を使うと札幌・函館だけが別扱いされる
    という無意味な区別が入ってしまう。
    """
    c = COURSES.get(course)
    if c is None:
        return {}
    out = {
        "回り": c.mawari,
        "小回り": c.kibo,
        "坂": c.saka,
        "直線": chokusen_band(course) or "",
    }
    if surface is None or surface.startswith("芝"):
        out["芝種"] = c.shiba
    return {k: v for k, v in out.items() if v}


def shares_trait(a: str, b: str, axis: str, surface: str | None = None) -> bool:
    """2場が同じ軸で同じ値を持つか（a の実績を b の予想に使えるか）。"""
    ta, tb = traits(a, surface), traits(b, surface)
    return axis in ta and axis in tb and ta[axis] == tb[axis]


def same_trait_courses(course: str, axis: str,
                       surface: str | None = None) -> list[str]:
    """その軸で同じ値を持つ競馬場の一覧（自分を含む）。"""
    return [name for name in COURSES
            if shares_trait(name, course, axis, surface)]
